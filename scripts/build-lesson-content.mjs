import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const projectRoot = resolve(import.meta.dirname, "..");
const manifestPath = resolve(projectRoot, "lesson-manifest.js");
const outputPath = resolve(projectRoot, "lesson-content.js");
const manifest = readFileSync(manifestPath, "utf8");
const lessonPaths = [...manifest.matchAll(/"([^"\n]+\.mdx)"/g)].map(match => match[1]);

const lessons = lessonPaths.map(path => ({
  path,
  raw: readFileSync(resolve(projectRoot, path), "utf8")
}));

writeFileSync(outputPath, `// Generated by scripts/build-lesson-content.mjs. Do not edit by hand.\nwindow.lessonContent = ${JSON.stringify(lessons)};\n`);
console.log(`Bundled ${lessons.length} lesson sources into lesson-content.js`);
